"""Outlines Anton's F and B (assets/og/anton-latin-400.ttf, SIL OFL) into SVG path data for the FB monogram.

Writes lib/monogram-glyphs.ts: each glyph normalised to its own box, cap height 100 units, y pointing down,
so the monogram never depends on the font being installed. Run: python3 scripts/monogram-glyphs.py
"""
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

FONT = "assets/og/anton-latin-400.ttf"
OUT = "lib/monogram-glyphs.ts"
CAP = 100

font = TTFont(FONT)
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
cap_height = font["OS/2"].sCapHeight
scale = CAP / cap_height

entries = []
for char in "FB":
    glyph = glyph_set[cmap[ord(char)]]
    bounds = BoundsPen(glyph_set)
    glyph.draw(bounds)
    x_min = bounds.bounds[0]
    width = (bounds.bounds[2] - x_min) * scale
    pen = SVGPathPen(glyph_set, ntos=lambda value: f"{value:.2f}".rstrip("0").rstrip("."))
    glyph.draw(TransformPen(pen, (scale, 0, 0, -scale, -x_min * scale, cap_height * scale)))
    entries.append(f'  {char}: {{ width: {width:.2f}, d: "{pen.getCommands()}" }},')

with open(OUT, "w", encoding="utf-8") as out:
    out.write("// Generated by scripts/monogram-glyphs.py from Anton (SIL OFL); do not edit by hand.\n")
    out.write(f"/** Anton F and B outlines, cap height {CAP} units, y down, each starting at x = 0. */\n")
    out.write("export const MONOGRAM_GLYPHS = {\n" + "\n".join(entries) + "\n} as const;\n")
print(f"wrote {OUT}")
